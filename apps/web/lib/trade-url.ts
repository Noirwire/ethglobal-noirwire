export function parseTradeUrl(raw: string | undefined): string | null {
  const value = raw?.trim();
  if (!value) return null;
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:" ? url.toString() : null;
  } catch {
    return null;
  }
}

export const TRADE_URL = parseTradeUrl(process.env.NEXT_PUBLIC_TRADE_URL);
